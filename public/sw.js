// Service worker: shows pushed notifications and opens the app when one is tapped.
// Registered by src/components/push-toggle.tsx. Payload: { id, title, body, url, tag }.

self.addEventListener("push", (event) => {
  const data = event.data ? event.data.json() : {};
  event.waitUntil(
    self.registration.showNotification(data.title ?? "Braina", {
      body: data.body,
      icon: "/favicon.ico",
      // Same-kind notifications replace each other instead of piling up.
      tag: data.tag,
      renotify: !!data.tag,
      data: { url: data.url ?? "/" },
    }),
  );
});

self.addEventListener("notificationclick", (event) => {
  event.notification.close();
  const url = new URL(event.notification.data?.url ?? "/", self.location.origin).href;
  event.waitUntil(
    (async () => {
      const windows = await self.clients.matchAll({ type: "window", includeUncontrolled: true });
      const open = windows.find((w) => new URL(w.url).origin === self.location.origin);
      if (open) {
        await open.focus();
        return open.navigate(url);
      }
      return self.clients.openWindow(url);
    })(),
  );
});
