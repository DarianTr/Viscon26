/** Shapes shared by the backend (data layer, route handlers) and the frontend. */

export type Item = {
  id: string;
  title: string;
  done: boolean;
  createdAt: string;
};

/** Study session types: what the student is working on in the block. */
export type SessionType = "theory" | "exercises" | "mock_exam" | "quiz";

/** Everything the calendar can show. */
/**
 * "buffer" is the daily catch-up block and "break" covers breaks and meals —
 * on the calendar, but not focused study.
 */
export type EventType = SessionType | "lecture" | "exam" | "buffer" | "break";

/** What a calendar block is for; null for entries created before activities existed. */
export const blockActivities = [
  "study",
  "mock_exam",
  "mock_review",
  "cheatsheet",
  "exam_eve",
  "short_break",
  "lunch",
  "dinner",
  "buffer",
  "exam",
  "quiz",
] as const;
export type BlockActivity = (typeof blockActivities)[number];

/** A subject's preparation phase: Foundation → Build → Peak → Taper. */
export type PrepPhaseName = "foundation" | "build" | "peak" | "taper";

export type Task = {
  id: string;
  type: SessionType;
  activity: BlockActivity | null;
  userPlanId: string | null;
  subject: string;
  title: string;
  detail: string | null;
  /** Planned duration in minutes. */
  minutes: number;
  /** Actual minutes studied — null until the session is completed. */
  actualMinutes: number | null;
  /** Start time, "HH:MM" in the users' time zone. */
  time: string;
  done: boolean;
  /** The student chose not to do it. */
  skipped: boolean;
  /** Added by hand rather than generated by a plan, so it can be edited and deleted. */
  manual: boolean;
};

export type PlanPhase = { name: string; weeks: number };

export type Plan = {
  id: string;
  title: string;
  subject: string;
  goal: string;
  weeks: number;
  hoursPerWeek: number;
  level: "Beginner" | "Intermediate" | "Advanced";
  gradient: string;
  phases: PlanPhase[];
  enrolled: number;
};

export type ActivePlan = {
  plan: Plan;
  currentWeek: number;
  examDate: string | null;
  /** Monday first. */
  weekSessions: { day: string; type: SessionType | null; done: boolean }[];
};

export type CalendarEvent = {
  id: string;
  type: EventType;
  activity: BlockActivity | null;
  /** Null for breaks and buffers. */
  subject: string | null;
  /** The plan this event belongs to, used for quiz navigation. */
  planId: string | null;
  /** Minutes of the block reserved for the cheatsheet, and the milestone it aims for. */
  cheatsheetMinutes: number | null;
  cheatsheetTarget: number | null;
  /** The subject's preparation phase at this block. */
  prepPhase: PrepPhaseName | null;
  title: string;
  /** ISO timestamp. */
  start: string;
  /** ISO timestamp: start + minutes. */
  end: string;
  minutes: number;
  calendarOrder: number | null;
  done: boolean;
  /** The student chose not to do it; it stays on the calendar, dimmed. */
  skipped: boolean;
  /** Added by hand rather than generated by a plan, so it can be edited and deleted. */
  manual: boolean;
};

export type UserSummary = { id: string; name: string; initials: string; hue: number };

export type Activity = {
  id: string;
  user: UserSummary;
  postedAgo: string;
  location: string | null;
  title: string;
  type: SessionType;
  subject: string;
  minutes: number;
  focus: number | null;
  trace: number[] | null;
  kudos: number;
  /** Whether the current user gave kudos. */
  kudoed: boolean;
  comments: number;
  note: string | null;
  /** URLs of the post's photos, oldest first. */
  photos: { id: string; url: string }[];
  /** Friends the author studied with. */
  tagged: UserSummary[];
  mine: boolean;
  /** False for private sessions, which only their author sees. */
  shared: boolean;
};

export type Comment = {
  id: string;
  user: UserSummary;
  body: string;
  postedAgo: string;
  /** The current user wrote it. */
  mine: boolean;
  /** The current user may delete it: their own comment, or one on their activity. */
  canDelete: boolean;
};

/**
 * Where someone stands with you: friends, a request you sent, a request they
 * sent you, or nothing yet.
 */
export type FriendStatus = "friends" | "sent" | "received" | "none";

/** Someone in friend search. */
export type Person = UserSummary & {
  handle: string;
  program: string | null;
  status: FriendStatus;
};

export type LeaderboardEntry = UserSummary & { hours: number; you: boolean };

export type Profile = {
  name: string;
  initials: string;
  hue: number;
  spiritAnimal: string;
  handle: string;
  program: string | null;
  friends: number;
  streak: number;
  /** Decays when the plan isn't followed (or there's no plan and no studying); vacations freeze it. */
  mascotHealth: { health: number; status: "thriving" | "steady" | "slipping" | "neglected" };
  totals: { hours: number; sessions: number; kudos: number };
  /** Hours logged per day this week, Monday first. */
  week: number[];
  /** This week's target, from the active study plans — see `src/lib/weekly-goal.ts`. */
  weeklyGoal: WeeklyGoal;
  /** Academic subjects only — breaks and buffers are never subjects. */
  subjects: { name: string; hours: number; minutes: number; examHoursRemaining: number | null }[];
  badges: { emoji: string; label: string; earned: boolean }[];
};

/**
 * The Profile's weekly target. "plan": focused hours the active plans schedule
 * this week (`planned` per day, Monday first; null for template plans, which
 * only have a weekly figure). "upcoming": no plan runs this week, but one
 * starts later. "none": no active plan.
 */
export type WeeklyGoal =
  | { kind: "plan"; hours: number; planned: number[] | null; plans: string[] }
  | { kind: "upcoming"; plan: string; start: string }
  | { kind: "none" };

/** A user as returned by /api/users. */
export type User = {
  id: string;
  handle: string;
  name: string;
  hue: number;
  spiritAnimal: string;
  program: string | null;
  weeklyGoalHours: number;
  createdAt: string;
};

/**
 * A task as returned by /api/tasks: one row of the sessions table, i.e. a
 * planned study session, lecture or exam. Done once `completedAt` is set.
 */
export type TaskRecord = {
  id: string;
  userId: string;
  planId: string | null;
  /** The student's own plan it belongs to. */
  userPlanId: string | null;
  type: EventType;
  activity: BlockActivity | null;
  /** Null for breaks and buffers. */
  subject: string | null;
  cheatsheetTarget: number | null;
  cheatsheetMinutes: number | null;
  prepPhase: PrepPhaseName | null;
  title: string;
  detail: string | null;
  scheduledAt: string;
  plannedMinutes: number;
  calendarOrder: number | null;
  done: boolean;
  completedAt: string | null;
  skipped: boolean;
  skippedAt: string | null;
  actualMinutes: number | null;
  focus: number | null;
  trace: number[] | null;
  location: string | null;
  note: string | null;
  shared: boolean;
  /** Added by hand rather than generated by a plan, so it can be edited and deleted. */
  addedManually: boolean;
  createdAt: string;
};

/** A subject to pick when adding a session by hand, with the newest plan that has it. */
export type SubjectChoice = { name: string; planId: string; planTitle: string };

export type ChallengeStatus = "pending" | "accepted" | "declined" | "completed";

/** A dare to match one of the challenger's sessions, from either side. */
export type Challenge = {
  id: string;
  status: ChallengeStatus;
  message: string | null;
  sentAgo: string;
  /** The other person: the challenger on received ones, the challengee on sent ones. */
  other: UserSummary;
  /** What has to be beaten. */
  source: { title: string; type: SessionType; subject: string | null; minutes: number; focus: number | null };
  /** How the challengee did, once completed. */
  result: { minutes: number; focus: number | null } | null;
};

export type NudgeStyle = "savage" | "gentle" | "off";
